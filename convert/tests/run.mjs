// node convert/tests/run.mjs
import { parse, convert, format, findUnit, UNITS, CATEGORIES } from "../js/units.js";
let passed = 0, failed = 0;
const ok = (c, m) => (c ? passed++ : (failed++, console.log("  FAIL", m)));
const run = (q) => {
  const p = parse(q);
  return p?.to ? convert(p.value, p.from, p.to) : p;
};
const near = (q, want, tol = 1e-6) => {
  const got = run(q);
  ok(typeof got === "number" && Math.abs(got - want) <= Math.abs(want) * tol + 1e-12, `${q}: ${JSON.stringify(got)} (want ${want})`);
};
near("100km to yards", 109361.329833771);
near("68F to C", 20);
near("68 °F in celsius", 20);
near("-40 c to f", -40);
near("0 K to C", -273.15);
near("1 kg to pounds", 2.20462262185);
near("100 grams to stone", 0.0157473044);
near("1 PB to KB", 1e12);
near("1 kilobyte to petabytes", 1e-12);
near("1 GiB to MB", 1073.741824);
near("100 Mb to MB", 12.5);
near("100 MB to Mb", 800);
near("50 mpg uk to mpg us", 41.6337);
near("50 mpg to l/100km", 5.64962, 1e-5);
near("6 L/100km to mpg", 47.0801560553, 1e-6);
near("5ft 10in to cm", 177.8);
near("5'10\" to cm", 177.8);
near("12st 7lb to kg", 79.3786648);
near("1,000 m in miles", 0.621371192237);
near("1 acre to m2", 4046.8564224);
near("1 sq mi to km²", 2.589988110336);
near("1 gallon to litres", 4.54609);
near("1 us gallon to litres", 3.785411784);
near("1 cubic ft to l", 28.316846592);
near("60 mph to km/h", 96.56064);
near("1 hp to kw", 0.745699872);
near("1 kwh to kcal", 860.420650096);
near("180 degrees to radians", Math.PI);
near("1 year to days", 365.2425);
near("30 psi to bar", 2.06842719);
near("1 light year to km", 9.4607304725808e12);
near("100 Nm to lb ft", 73.7562149);
near("3 in to cm", 7.62);
ok(parse("5 kg to metres").error.includes("don't convert"), "mass and length don't mix");
ok(parse("5 blorps to kg").error.includes("blorps"), "an unknown unit is named");
ok(parse("100 kg").to === null && parse("100 kg").from.sym === "kg", "no target: just the unit (show everything)");
ok(findUnit("KM").sym === "km" && findUnit("Kilometres").sym === "km" && findUnit("feet").sym === "ft" && findUnit("degrees F").sym === "°F", "units, however they're typed");
ok(UNITS.length >= 160 && CATEGORIES.length >= 16, `a big library: ${UNITS.length} units in ${CATEGORIES.length} categories`);
ok(format(1093.6133) === "1,093.6133" && format(1e18).includes("10\u00b9\u2078") && format(0.5) === "0.5", `friendly numbers: ${format(1093.6133)}, ${format(1e18)}`);
console.log(`\n${passed}/${passed + failed} passed`);
process.exit(failed ? 1 : 0);
